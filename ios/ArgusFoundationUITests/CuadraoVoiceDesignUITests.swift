    /// Checkpoint journey for the voice picker. It needs `--cuadrao-voice-selection` and the sample
    /// clips, which stay out while their licensing is unsettled (#785), so it is skipped until they land.
    func testVoiceChoiceAndProposalHandoff() throws {
        try XCTSkipIf(true, "Voice sample clips are excluded (licensing); voice selection stays off")
        continueAfterFailure = false
        let app = XCUIApplication.cuadraoPreview()
        app.launchArguments.append(CuadraoPreviewLaunch.voiceSelection)
        app.launch()
        app.buttons["tab.argus"].tap()
        app.buttons["chat-voice-entry"].tap()
        XCTAssertTrue(app.buttons["voice-minimize"].waitForExistence(timeout: 3))
        capture(app, "voice-expanded")
        app.buttons["voice-mute"].tap()
        XCTAssertEqual(app.staticTexts["voice-status"].label, "Micrófono silenciado")
        capture(app, "voice-muted")
        app.buttons["voice-mute"].tap()
        app.buttons["voice-choose"].tap()
        XCTAssertTrue(app.buttons["voice-option-sal"].waitForExistence(timeout: 3))
        // Opening preferences stays quiet; paging both selects and previews a voice.
        XCTAssertTrue(app.buttons["voice-sample"].label.hasPrefix("Escuchar"))
        app.buttons["voice-option-ara"].tap()
        swipeVoice(app.staticTexts["Ara"])
        XCTAssertEqual(app.buttons["voice-sample"].label, "Detener Eve")
        swipeVoice(app.staticTexts["Eve"])
        XCTAssertEqual(app.buttons["voice-sample"].label, "Detener Sal")
        app.buttons["voice-sample"].tap()
        XCTAssertEqual(app.buttons["voice-sample"].label, "Escuchar Sal")
        capture(app, "voice-carousel")
        app.buttons["voice-picker-done"].tap()
        app.buttons["voice-minimize"].tap()
        capture(app, "voice-compact")
        app.buttons["header.profile"].tap()
        app.buttons["Preferencias"].tap()
        app.collectionViews.firstMatch.swipeUp()
        capture(app, "preferences-before-voice")
        app.buttons["Voz"].tap()
        XCTAssertTrue(app.buttons["voice-preference"].waitForExistence(timeout: 3))
        XCTAssertEqual(app.buttons["voice-preference"].value as? String, "Sal")
        capture(app, "shared-voice-preference")
        app.buttons["voice-expand"].tap()
        app.buttons["voice-preview-info"].tap()
        app.buttons["Ver propuesta de ejemplo"].tap()
        XCTAssertTrue(app.buttons["Revisar propuesta"].waitForExistence(timeout: 3))
        XCTAssertTrue(app.buttons["voice-expand"].exists)
        capture(app, "proposal-in-plan")
        app.buttons["Revisar propuesta"].tap()
        app.buttons["Marcar como revisada"].tap()
        XCTAssertTrue(app.staticTexts["Revisada en la vista previa"].waitForExistence(timeout: 3))
        app.buttons["voice-end-compact"].tap()
        XCTAssertTrue(app.staticTexts["Revisada en la vista previa"].exists)
        app.terminate(); app.launch()
        app.buttons["header.profile"].tap()
        app.buttons["Preferencias"].tap(); app.collectionViews.firstMatch.swipeUp(); app.buttons["Voz"].tap()
        XCTAssertEqual(app.buttons["voice-preference"].value as? String, "Sal")
    }
    func testHoldComposerAndWaveformWithoutStartingLiveVoice() {
        continueAfterFailure = false
        let app = XCUIApplication.cuadraoPreview()
        app.launch()
        app.buttons["tab.argus"].tap()
        XCTAssertTrue(app.buttons["chat-composer-entry"].waitForExistence(timeout: 3))
        app.buttons["chat-composer-entry"].press(forDuration: 1.2)
        XCTAssertEqual(app.staticTexts["voice-message-status"].label, "Mensaje de voz · Vista previa")
        XCTAssertFalse(app.buttons["voice-minimize"].exists)
        capture(app, "voice-message-released")
        app.buttons["Descartar"].tap()
        let entry = app.buttons["chat-voice-entry"]
        let origin = entry.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5))
        origin.press(forDuration: 0.7, thenDragTo: origin.withOffset(CGVector(dx: -130, dy: 0)),
                     withVelocity: .slow, thenHoldForDuration: 1)
        XCTAssertFalse(app.staticTexts["voice-message-status"].exists)
        XCTAssertFalse(app.buttons["voice-minimize"].exists)
        entry.press(forDuration: 1.2)
        XCTAssertEqual(app.staticTexts["voice-message-status"].label, "Mensaje de voz · Vista previa")
        app.buttons["Descartar"].tap()
        app.buttons["chat-composer-entry"].tap()
        XCTAssertTrue(app.buttons["chat-dismiss-keyboard"].waitForExistence(timeout: 3))
        let field = app.descendants(matching: .any)["chat-composer"].firstMatch
        field.typeText("Mi plan")
        XCTAssertTrue(app.buttons["chat-send"].exists)
        field.press(forDuration: 1)
        XCTAssertFalse(app.staticTexts["voice-message-status"].exists)
        XCTAssertFalse(app.buttons["voice-minimize"].exists)
        capture(app, "typed-draft-preserved")
    }
    func testLockedRecordingAndCleanAttachments() {
        continueAfterFailure = false
        let app = XCUIApplication.cuadraoPreview()
        app.launch()
        app.buttons["tab.argus"].tap()
        app.buttons["chat-attach"].tap()
        XCTAssertFalse(app.buttons["chat-voice-message"].exists)
        for label in ["Escanear", "Foto", "Archivo"] { XCTAssertTrue(app.buttons[label].exists) }
        capture(app, "attachments-only")
        app.buttons["chat-attach"].tap()
        for target in ["chat-composer-entry", "chat-voice-entry"] {
            lockRecording(app.buttons[target])
            XCTAssertTrue(app.buttons["voice-message-stop"].waitForExistence(timeout: 3))
            XCTAssertFalse(app.buttons["tab.home"].exists)
            XCTAssertFalse(app.buttons["voice-minimize"].exists)
            // SF Symbol accessibility bounds can differ slightly from the layout box.
            XCTAssertEqual(app.descendants(matching: .any)["voice-recording-timer"].firstMatch.frame.midX, app.frame.midX, accuracy: 2)
            capture(app, "locked-" + target)
            app.buttons["voice-message-stop"].tap()
            XCTAssertEqual(app.staticTexts["voice-message-status"].label, "Revisar mensaje · Vista previa")
            XCTAssertTrue(app.buttons["header.profile"].waitForExistence(timeout: 3))
            app.buttons["header.profile"].tap()
            app.buttons["tab.argus"].tap()
            XCTAssertEqual(app.staticTexts["voice-message-status"].label, "Revisar mensaje · Vista previa")
            capture(app, "review-preserved")
            app.buttons["Descartar"].tap()
        }
        lockRecording(app.buttons["chat-voice-entry"])
        app.buttons["voice-message-cancel"].tap()
        XCTAssertTrue(app.buttons["header.profile"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.staticTexts["voice-message-status"].exists)
    }
    private func lockRecording(_ target: XCUIElement) {
        let origin = target.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5))
        origin.press(forDuration: 0.7, thenDragTo: origin.withOffset(CGVector(dx: 0, dy: -135)),
                     withVelocity: .slow, thenHoldForDuration: 0.5)
    }
    func testEnglishVoiceAndLargeText() {
        continueAfterFailure = false
        let app = XCUIApplication.cuadraoPreview()
        app.launchArguments = CuadraoPreviewLaunch.arguments + ["--design-english", "-AppleInterfaceStyle", "Dark"]
        app.launch()
        app.buttons["tab.argus"].tap()
        XCTAssertEqual(app.buttons["chat-composer-entry"].label, "Type or hold to speak")
        capture(app, "english-composer")
        lockRecording(app.buttons["chat-voice-entry"])
        XCTAssertTrue(app.buttons["voice-message-stop"].waitForExistence(timeout: 3))
        XCTAssertEqual(app.buttons["voice-message-stop"].label, "Stop")
        XCTAssertEqual(app.descendants(matching: .any)["voice-recording-timer"].firstMatch.frame.midX, app.frame.midX, accuracy: 2)
        capture(app, "locked-english")
        app.buttons["voice-message-stop"].tap()
        app.buttons["Discard"].tap()
        app.buttons["chat-voice-entry"].tap()
        XCTAssertEqual(app.staticTexts["voice-status"].label, "I'm listening")
        capture(app, "english-voice-expanded")
        app.buttons["voice-minimize"].tap()
        XCTAssertTrue(app.buttons["voice-expand"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.buttons["chat-voice-entry"].exists)
        capture(app, "english-voice-compact")
        app.buttons["voice-end-compact"].tap()
        app.terminate()
        app.launchArguments = CuadraoPreviewLaunch.arguments + ["-UIPreferredContentSizeCategoryName", "UICTContentSizeCategoryAccessibilityXXXL"]
        app.launch()
        app.buttons["tab.argus"].tap()
        app.buttons["chat-voice-entry"].tap()
        XCTAssertTrue(app.buttons["voice-minimize"].isHittable)
        app.scrollViews.firstMatch.swipeUp()
        XCTAssertTrue(app.buttons["voice-end"].isHittable)
        capture(app, "voice-large-text")
        app.buttons["voice-end"].tap()
        XCTAssertTrue(app.buttons["chat-voice-entry"].waitForExistence(timeout: 3))
        lockRecording(app.buttons["chat-voice-entry"])
        XCTAssertTrue(app.buttons["voice-message-stop"].waitForExistence(timeout: 3))
        capture(app, "locked-large-text")
        app.buttons["voice-message-stop"].tap()
        XCTAssertTrue(app.buttons["voice-message-send"].waitForExistence(timeout: 3))
    }
    private func swipeVoice(_ title: XCUIElement) {
        let center = title.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5))
        center.withOffset(CGVector(dx: 120, dy: 0)).press(forDuration: 0.05,
            thenDragTo: center.withOffset(CGVector(dx: -120, dy: 0)))
    }
    private func capture(_ app: XCUIApplication, _ name: String) {
        let item = XCTAttachment(screenshot: app.screenshot())
        item.name = name; item.lifetime = .keepAlways; add(item)
    }

}
