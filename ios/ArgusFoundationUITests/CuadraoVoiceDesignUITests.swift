import XCTest

final class CuadraoVoiceDesignUITests: XCTestCase {
    func testVoiceStaysAvailableAcrossSheetsAndSurfaces() {
        continueAfterFailure = false
        let app = XCUIApplication.cuadraoPreview()
        app.launch()
        XCTAssertTrue(app.buttons["tab.argus"].waitForExistence(timeout: 8))
        app.buttons["tab.argus"].tap()
        XCTAssertTrue(app.buttons["chat-voice-entry"].waitForExistence(timeout: 5))
        app.buttons["chat-voice-entry"].tap()
        XCTAssertTrue(app.buttons["voice-minimize"].waitForExistence(timeout: 3))
        let center = app.staticTexts["voice-status"].coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5))
        center.press(forDuration: 0.05, thenDragTo: center.withOffset(CGVector(dx: 0, dy: 160)))
        XCTAssertTrue(app.buttons["voice-expand"].waitForExistence(timeout: 3))
        app.buttons["voice-expand"].tap()
        app.buttons["voice-keyboard"].tap()
        XCTAssertTrue(app.buttons["chat-dismiss-keyboard"].waitForExistence(timeout: 3))
        app.buttons["chat-dismiss-keyboard"].tap()
        XCTAssertTrue(app.buttons["header.profile"].waitForExistence(timeout: 3))
        app.buttons["voice-mute-compact"].tap()
        XCTAssertTrue(app.staticTexts["Silenciado"].exists)
        app.buttons["voice-mute-compact"].tap()
        app.buttons["header.profile"].tap()
        XCTAssertTrue(app.buttons["cuadrao.profile.identity"].waitForExistence(timeout: 3))
        XCTAssertTrue(app.buttons["voice-expand"].exists)
        app.buttons["voice-end-compact"].tap()
        XCTAssertFalse(app.buttons["voice-expand"].exists)
        let capture = XCTAttachment(screenshot: app.screenshot())
        capture.name = "profile-after-voice"; capture.lifetime = .keepAlways; add(capture)
    }
